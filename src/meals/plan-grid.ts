/** meal_plan_entries row (verified shape, wave1-endpoints.md Meals row). */
export interface MealRow {
  id: string | number;
  name: string;
  emoji: string;
  /** Weekday short "Mon".."Sun" — where the meal lands in the week grid. */
  time: string;
  mealType?: MealSlotId;
  prepTime: string;
  /** JSON-stringified by PB; parsed on read (meal-rows.ts parity). */
  tags?: unknown;
  ingredients?: unknown;
  servings: number;
  calories: number;
  protein?: number;
  carbs?: number;
  fat?: number;
  instructions?: string;
  autoGenerated?: boolean;
  recipeId?: string;
  recipeSnapshotAt?: string;
  /** Monday of the planned week, "YYYY-MM-DD". Missing = current week. */
  weekOf?: string;
  date?: string;
}

/** A row after parse — tags/ingredients are real string arrays. */
export interface ParsedMeal extends MealRow {
  tags: string[];
  ingredients: string[];
}

/**
 * Port of Home-ai src/lib/meal-rows.ts parseArrayField: PB stores the arrays
 * JSON-stringified; a bad payload degrades to [] (never a crash, never a
 * raw JSON string on the wall).
 */
export function parseArrayField(value: unknown): string[] {
  if (Array.isArray(value)) return value.filter((v): v is string => typeof v === "string");
  if (typeof value === "string" && value) {
    try {
      const parsed = JSON.parse(value);
      if (Array.isArray(parsed)) return parsed.filter((v): v is string => typeof v === "string");
    } catch {
      /* fall through to empty */
    }
  }
  return [];
}

/** meal-rows.ts mapMealRows parity: parse tags/ingredients on read. */
export function mapMealRows(rows: MealRow[]): ParsedMeal[] {
  return rows.map((meal) => ({
    ...meal,
    tags: parseArrayField(meal.tags),
    ingredients: parseArrayField(meal.ingredients),
  }));
}

/**
 * The current slot by hour band — PlanTab's timeOfDayMeal thresholds
 * (<10 breakfast, <14 lunch, <17 snack, else dinner). Same bands the
 * CurrentMealWidget's fallback rules use, so the cell and the page agree.
 */
export function currentSlotForHour(hour: number): MealSlotId {
  if (hour < 10) return "breakfast";
  if (hour < 14) return "lunch";
  if (hour < 17) return "snack";
  return "dinner";
}

/**
 * Cell pick — the CurrentMealWidget's selection semantics verbatim:
 * (m.weekOf ?? currentWeekMonday) === currentWeekMonday && m.time === day &&
 * m.mealType === slot. A missing weekOf means "the week it was written in"
 * (web parity); no cross-slot fallback.
 */
export function mealForCell(
  meals: ParsedMeal[],
  day: string,
  slot: MealSlotId,
  weekMonday: string
): ParsedMeal | undefined {
  return meals.find(
    (m) => (m.weekOf ?? weekMonday) === weekMonday && m.time === day && m.mealType === slot
  );
}

/** Does this week (Monday key) hold any planned meal? Drives the empty state. */
export function weekHasMeals(meals: ParsedMeal[], weekMonday: string): boolean {
  return meals.some((m) => (m.weekOf ?? weekMonday) === weekMonday);
}

function isoToDate(iso: string): Date {
  const [y, m, d] = iso.split("-").map(Number);
  return new Date(y, m - 1, d);
}

/** Local YYYY-MM-DD (mirrors widgets/data.ts localTodayISO). */
export function isoForDate(d: Date): string {
  const y = d.getFullYear();
  const m = String(d.getMonth() + 1).padStart(2, "0");
  const day = String(d.getDate()).padStart(2, "0");
  return `${y}-${m}-${day}`;
}

/** ISO + n days (calendar-page math parity). */
export function addDaysISO(iso: string, days: number): string {
  const d = isoToDate(iso);
  d.setDate(d.getDate() + days);
  return isoForDate(d);
}
